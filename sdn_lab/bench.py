"""
bench.py -- performance evaluation: SDN-enforced network vs a static (learning-switch) baseline.

    sudo python3 sdn_lab/bench.py            # about 4 minutes
    sudo python3 sdn_lab/bench.py --quick

Experiments (each run once per controller mode, on a fresh network)
  E1  legit client under link conditions   request latency p50/p95 and bulk throughput for h1 (alice)
                                           at 2 ms / 20 ms / 20 ms+1 % loss / 50 ms+5 % loss
  E2  misbehaving host (flood)             h3 sends denied requests as fast as it can for N s while h1 works:
                                           h1's latency, how many of h3's requests reached the proxy, how soon
                                           the network cut h3 off
  E3  proxy bypass                         h2 tries to open 5 TCP connections straight to the services host

Writes logs/mininet/bench.json, sdn_lab/RESULTS.md and (with matplotlib) sdn_lab/charts/*.png.
"""
import argparse
import json
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from lab import IPS, OUT, Lab  # noqa: E402

HERE = Path(__file__).resolve().parent
CONDITIONS = [("2ms", 0), ("20ms", 0), ("20ms", 1), ("50ms", 5)]


def e1(lab, n, nbytes):
    rows = []
    for delay, loss in CONDITIONS:
        lab.set_client_link("h1", delay=delay, loss=loss)
        time.sleep(1)
        lat = lab.loadgen("h1", f"latency --user {{user}} -n {n} --timeout 30", timeout=300)
        bulk = lab.loadgen("h1", f"bulk --user {{user}} --bytes {nbytes}", timeout=300)
        rows.append({"delay": delay, "loss_pct": loss, "p50_ms": lat["p50_ms"], "p95_ms": lat["p95_ms"],
                     "errors": lat["errors"], "mbit_s": bulk["mbit_s"]})
        print(f"   E1 {delay:>5} loss {loss}%: p50 {lat['p50_ms'] or 0:6.1f} ms  p95 {lat['p95_ms'] or 0:6.1f} ms  "
              f"{bulk['mbit_s']:5.2f} Mbit/s")
    lab.set_client_link("h1")
    return rows


def e2(lab, duration):
    t0 = time.time()
    flood = lab.loadgen_bg("h3", f"flood --duration {duration} --workers 4")
    time.sleep(1)
    lat = lab.loadgen("h1", f"latency --user {{user}} -n {int(duration * 3)} --gap 0.2 --timeout 5", timeout=300)
    out = flood.communicate(timeout=duration + 60)[0]
    fl = json.loads(out.strip().splitlines()[-1])
    seen = 0
    log = OUT / f"access_{lab.mode}.log"
    if log.exists():
        for line in log.read_text().splitlines():
            try:
                r = json.loads(line)
            except ValueError:
                continue
            if r.get("src") == IPS["h3"] and "decision" in r:
                seen += 1
    block = next((e for e in lab.sdn_events() if e["event"] == "block" and e["ip"] == IPS["h3"]), None)
    row = {"flood_denied_by_proxy": fl.get("denied", 0), "flood_network_errors": fl.get("errors", 0),
           "proxy_decisions_for_h3": seen, "cutoff_after_s": (block["ts"] - t0) if block else None,
           "legit_p50_ms": lat["p50_ms"], "legit_p95_ms": lat["p95_ms"], "legit_errors": lat["errors"]}
    print(f"   E2 proxy handled {seen} of h3's requests; cut-off after "
          f"{row['cutoff_after_s'] if row['cutoff_after_s'] is None else round(row['cutoff_after_s'], 2)} s; "
          f"h1 p95 {lat['p95_ms'] or 0:.1f} ms")
    return row


def e3(lab):
    ok = sum(lab.reachable("h2", IPS["svc"], 9001, timeout=2) for _ in range(5))
    print(f"   E3 direct connections to the services host that succeeded: {ok}/5")
    return {"direct_success": ok, "attempts": 5}


def table(r):
    s, b = r["sdn"], r["static"]
    L = ["# Results: SDN-enforced network vs static baseline", "",
         "Generated by `sdn_lab/bench.py`. *static* = controller acts as a plain learning switch; *sdn* = ACL + quarantine.", "",
         "## E1 - legitimate client under link conditions", "",
         "| delay | loss | p50 static | p50 SDN | p95 static | p95 SDN | Mbit/s static | Mbit/s SDN |", "|---|---|---|---|---|---|---|---|"]
    for x, y in zip(b["e1"], s["e1"]):
        f = lambda v: "-" if v is None else f"{v:.1f}"
        L.append(f"| {x['delay']} | {x['loss_pct']} % | {f(x['p50_ms'])} | {f(y['p50_ms'])} | {f(x['p95_ms'])} | {f(y['p95_ms'])} | {x['mbit_s']:.2f} | {y['mbit_s']:.2f} |")
    L += ["", "## E2 - flooding host", "", "| metric | static | SDN |", "|---|---|---|"]
    for k, label in (("proxy_decisions_for_h3", "requests from h3 that reached the proxy"), ("flood_network_errors", "h3 requests dropped in the network"),
                     ("cutoff_after_s", "seconds until h3 was cut off"), ("legit_p50_ms", "h1 p50 latency during flood (ms)"),
                     ("legit_p95_ms", "h1 p95 latency during flood (ms)"), ("legit_errors", "h1 failed requests")):
        g = lambda v: "never" if v is None and k == "cutoff_after_s" else ("-" if v is None else (f"{v:.1f}" if isinstance(v, float) else str(v)))
        L.append(f"| {label} | {g(b['e2'][k])} | {g(s['e2'][k])} |")
    L += ["", "## E3 - bypassing the proxy", "", "| | static | SDN |", "|---|---|---|",
          f"| direct connections to services that succeeded | {b['e3']['direct_success']}/5 | {s['e3']['direct_success']}/5 |", ""]
    return "\n".join(L)


def charts(r):
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except ImportError:
        print("matplotlib not installed - skipping charts")
        return
    d = HERE / "charts"
    d.mkdir(exist_ok=True)
    labels = [f"{c['delay']}\n{c['loss_pct']}% loss" for c in r["sdn"]["e1"]]
    xs = range(len(labels))
    fig, ax = plt.subplots(figsize=(7, 4))
    ax.bar([x - 0.2 for x in xs], [c["p95_ms"] or 0 for c in r["static"]["e1"]], 0.4, label="static")
    ax.bar([x + 0.2 for x in xs], [c["p95_ms"] or 0 for c in r["sdn"]["e1"]], 0.4, label="SDN")
    ax.set_xticks(list(xs), labels)
    ax.set_ylabel("p95 request latency (ms)")
    ax.set_title("E1: legitimate client, SDN vs static")
    ax.legend()
    fig.tight_layout()
    fig.savefig(d / "e1_latency.png", dpi=130)
    fig, ax = plt.subplots(figsize=(5, 4))
    ax.bar(["static", "SDN"], [r["static"]["e2"]["proxy_decisions_for_h3"], r["sdn"]["e2"]["proxy_decisions_for_h3"]], color=["#999", "#2a7"])
    ax.set_ylabel("flood requests the proxy had to process")
    ax.set_title("E2: load reaching the proxy")
    fig.tight_layout()
    fig.savefig(d / "e2_proxy_load.png", dpi=130)
    print(f"charts in {d}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--quick", action="store_true")
    a = ap.parse_args()
    n, nbytes, dur = (10, 500_000, 8) if a.quick else (30, 2_000_000, 15)
    result = {}
    for mode in ("static", "sdn"):
        print(f"\n== controller mode: {mode} ==")
        with Lab(mode=mode, threshold=5, window=10, block_seconds=120) as lab:
            result[mode] = {"e1": e1(lab, n, nbytes)}
            result[mode]["e3"] = e3(lab)
            result[mode]["e2"] = e2(lab, dur)
    (OUT / "bench.json").write_text(json.dumps(result, indent=2))
    md = table(result)
    (HERE / "RESULTS.md").write_text(md)
    print("\n" + md)
    charts(result)


if __name__ == "__main__":
    main()
